// Writes the "Built with" section of README.md from src/data/credits.js (same list as the "About" page),
// purpose texts from the English language file. Replaces only the part between <!-- credits:start --> and
// <!-- credits:end -->. Runs before every build (npm "prebuild") – commit the README afterwards.
import fs from 'node:fs';
import { RUNTIME, ASSETS, BUILD } from '../src/data/credits.js';

const root = new URL('../', import.meta.url);
const readmeUrl = new URL('README.md', root);
const about = JSON.parse(fs.readFileSync(new URL('src/i18n/en.json', root), 'utf8')).about;

const cell = text => String(text).replace(/\|/g, '\\|');
const table = (title, items) => [
  `### ${title}`,
  '',
  '| Project | Used for | License |',
  '|---|---|---|',
  ...items.map(i => `| [${cell(i.name)}](${i.url}) | ${cell(about.libs[i.id] ?? '')} | ${cell(i.license)} |`),
  '',
].join('\n');

const section = [
  '<!-- credits:start – generated by scripts/sync-readme.mjs from src/data/credits.js, do not edit by hand -->',
  about.openSource,
  '',
  table(about.runtime, RUNTIME),
  table(about.assets, ASSETS),
  table(about.build, BUILD),
  '<!-- credits:end -->',
].join('\n');

const readme = fs.readFileSync(readmeUrl, 'utf8');
const pattern = /<!-- credits:start[\s\S]*?<!-- credits:end -->/;
if (!pattern.test(readme)) throw new Error('README.md: markers <!-- credits:start --> … <!-- credits:end --> missing');
const updated = readme.replace(pattern, () => section);
if (updated !== readme) {
  fs.writeFileSync(readmeUrl, updated);
  console.log('README.md: "Built with" updated from credits.js');
}
